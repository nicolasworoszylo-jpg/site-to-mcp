// ai.txt (eksperymentalne, niska adopcja, generujemy bo wolne 2 KB ROI)
// ============================================================================

export interface AiTxtInput {
  siteUrl: string;
  /** Polityka użycia: allow training / disallow training / require attribution */
  policy: 'allow' | 'disallow' | 'require_attribution';
  contact?: string;
}

export function generateAiTxt(input: AiTxtInput): string {
  const lines: string[] = [];
  lines.push(`# ai.txt — AI usage policy`);
  lines.push(`# Site: ${input.siteUrl}`);
  lines.push('');
  lines.push(`Policy: ${input.policy}`);
  if (input.contact) lines.push(`Contact: ${input.contact}`);
  lines.push('');
  lines.push('# This file is experimental and not widely adopted as of 2026.');
  lines.push('# Use robots.txt + Content-Signal headers as primary controls.');
  return lines.join('\n');
}
